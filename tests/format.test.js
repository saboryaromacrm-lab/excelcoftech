const assert = require('assert');
const XLSX = require('xlsx');
const C = require('../src/format.js');
const p = C.parseInput;
assert.deepStrictEqual(p('1234,56'), { value: 1234.56, format: undefined });
assert.deepStrictEqual(p('1.500'), { value: 1500, format: '#,##0' });
assert.strictEqual(p('1.234,5').value, 1234.5);
assert.strictEqual(p('12.5').value, 12.5);
assert.deepStrictEqual(p('$ 1.500,50'), { value: 1500.5, format: '"$" #,##0.00' });
assert.deepStrictEqual(p('21%'), { value: 0.21, format: '0%' });
assert.deepStrictEqual(p('15/03/2025'), { value: 45731, format: 'dd/mm/yyyy' });
assert.strictEqual(p('31/02/2025').text, true);
assert.strictEqual(p('Coca Cola 1,5L').text, true);
assert.strictEqual(p('=SUMA(A1;A2)').formula, true);
assert.strictEqual(p('VERDADERO').value, true);
const d = (v, f) => C.display(v, f, XLSX.SSF);
assert.strictEqual(d(1234.5, '"$" #,##0.00'), '$ 1.234,50');
assert.strictEqual(d(0.21, '0%'), '21%');
assert.strictEqual(d(45731, 'dd/mm/yyyy'), '15/03/2025');
assert.strictEqual(d(45731, 'm/d/yy'), '15/03/2025');
assert.strictEqual(d(1234.5678, ''), '1234,5678');
assert.strictEqual(d(1/3, 'General'), '0,3333333333');
assert.strictEqual(C.changeDecimals('"$" #,##0.00', 1), '"$" #,##0.000');
assert.strictEqual(C.changeDecimals('0.0%', -1), '0%');
assert.strictEqual(C.changeDecimals('0%', 1), '0.0%');
assert.strictEqual(C.changeDecimals('', 1, 2.5), '0.00');
assert.strictEqual(C.editText(0.21, '0%', XLSX.SSF), '21%');
assert.strictEqual(C.editText(1234.5, '"$" #,##0.00', XLSX.SSF), '1234,5');
console.log('format: ok');
